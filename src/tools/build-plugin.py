def keyframes(names):
    """The @keyframes the panel's own rules name, lifted from style.css.

    THE SPLITTER CARRIES RULES, NOT AT-RULES. `split_style.shell` keeps every
    rule whose selector names a class the panel prints, and `@keyframes` has no
    selector, so an animation the panel asks for arrived without its drawing:
    measured 2026-09-22 on a guest, `animation-name: reading-panel-rise` was set
    on every row of the panel and nothing moved, because the browser had never
    been told what that name means. Copied here at build time rather than by
    hand, so the two cannot drift.

    THE LIST GREW WHEN THE ROW-BY-ROW REVEAL WENT (2026-09-22, the roll). That
    animation was the only name here, and asking for it after it was gone made
    the build stop, which is the guard doing its job. The four names that took
    its place were all in the same position it had been in: the panel asks for
    them and no guest had ever been told what they mean, so the sheet turning
    between levels and the opening on a phone were both still.
    """
    half = (THEME / "style.css").read_text()
    out = []
    for name in names:
        at = half.find("@keyframes " + name)
        if at == -1:
            print(f"style.css has no @keyframes {name}, which the panel's reveal needs")
            raise SystemExit(1)
        depth, end = 0, at
        for i in range(at, len(half)):
            if half[i] == "{":
                depth += 1
            elif half[i] == "}":
                depth -= 1
                if depth == 0:
                    end = i + 1
                    break
        out.append(half[at:end])
    return ("\n" + "\n".join(out) + "\n") if out else ""


def stripper():
    """The theme zip's own comment stripper, so the plugin's scripts reach the
    server exactly as the theme's did: the reasoning stays in the repository."""
    spec = importlib.util.spec_from_file_location("build_dist", THEME / "tools" / "build-dist.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.strip_comments


def php_stripped(p: Path) -> bytes:
    """The shipped PHP without its working notes (2026-09-25, for wordpress.org:
    the comments quote private conversations and name files only this
    repository has). tools/php_strip.py does it, for the theme and Extras too;
    without a PHP binary the file ships whole, which is only ever a local build."""
    if not Path(PHP).is_file():
        return p.read_bytes()
    return php_strip.php(p)


def fonts() -> list[tuple[Path, str]]:
    """The font files plugin/fonts.json names, from the theme repo's
    assets/fonts/webfonts (where the lab and the kit still read them), and
    every licence text beside them: the OFL travels with its face."""
    import json

    data = json.loads((THEME / OWN / "fonts.json").read_text())
    names = sorted({src.split("/")[-1] for fam in data["fontFamilies"] for face in fam["fontFace"] for src in face["src"]})
    out = [(THEME / "assets/fonts/webfonts" / n, f"fonts/{n}") for n in names]
    # Every licence beside a face that travels. Newsreader and Inter joined
    # fonts.json in 0.9.0, so their licences travel too: on a theme that is not
    # Architrave neither face exists, and without them the panel drew itself in
    # the system sans and the default reading face fell back to Georgia.
    out += [(p, f"fonts/{p.name}") for p in sorted((THEME / "assets/fonts").glob("*-OFL.txt"))]
    return out


