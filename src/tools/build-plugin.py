    print(f"  {len(panel_css):>8}  {SLUG}/assets/css/panel.css (cut from style.css)")
    print(f"  {len(tokens_css):>8}  {SLUG}/assets/css/panel-tokens.css (tools/panel-tokens.py)")
    print(f"  {len(parts_css):>8}  {SLUG}/assets/css/panel-parts.css (the QDS parts it wears, for guests)")
    print(f"  {len(shell_css):>8}  {SLUG}/assets/css/panel-shell.css (the panel's frame, for guests)")
    print(f"  {len(guest_css):>8}  {SLUG}/assets/css/panel-guest.css (panel.css behind the guard, for guests)")
    print(f"  {len(page_css):>8}  {SLUG}/assets/css/panel-page.css (the role table, for guests)")
    print(f"wrote {target.relative_to(THEME)} ({target.stat().st_size} bytes)")
    if args.to:
        import shutil

        dest = Path(args.to).expanduser()
        dest.mkdir(parents=True, exist_ok=True)
        for child in dest.iterdir():
            if child.name in (".git", ".github", "README.md", "LICENSE", ".gitignore", ".wporg-assets"):
                continue  # .wporg-assets: the directory's screenshots/banner/icon, which live in SVN's assets/, never in the zip
            shutil.rmtree(child) if child.is_dir() else child.unlink()
        with zipfile.ZipFile(target) as z:
            for name in z.namelist():
                rel = name.split("/", 1)[1]
                if not rel:
                    continue
                out = dest / rel
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(z.read(name))
        # THE SOURCE BESIDE THE BUILD (2026-09-25, for wordpress.org). The
        # repository is public source, not withheld build output: src/ carries
        # the PHP and JS exactly as authored, comments and all, plus the tools
        # that turn them into what ships, and says what each generated sheet
        # is cut from. The shipped CSS itself is the plugin's stylesheet of
        # record: plain unminified rules, generated rule for rule.
        src = dest / "src"
        for p, rel in files:
            if p.suffix in (".php", ".js") or rel in ("readme.txt", "assets/css/door.css"):
                out = src / rel
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(p.read_bytes())
        (src / "assets" / "css").mkdir(parents=True, exist_ok=True)
        (src / "assets" / "css" / "panel-page.css").write_bytes((THEME / OWN / "assets" / "css" / "panel-page.css").read_bytes())
